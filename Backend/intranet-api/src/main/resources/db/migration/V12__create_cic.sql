
-- =========================================
-- CIC: Centro de Información Corporativa
-- =========================================

CREATE TABLE cic_categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300),
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cic_categoria_nombre UNIQUE (nombre)
);

CREATE TABLE cic_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    descripcion TEXT,

    categoria_id BIGINT NOT NULL,

    nombre_archivo VARCHAR(255) NOT NULL,
    ruta_archivo VARCHAR(500) NOT NULL,
    tipo_mime VARCHAR(150) NOT NULL,
    tamano_bytes BIGINT NOT NULL,

    estado VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',

    creado_por VARCHAR(50) NOT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    publicado_en TIMESTAMP,

    CONSTRAINT fk_cic_documento_categoria
        FOREIGN KEY (categoria_id)
        REFERENCES cic_categoria(id),

    CONSTRAINT fk_cic_documento_usuario
        FOREIGN KEY (creado_por)
        REFERENCES users(username),

    CONSTRAINT chk_cic_documento_estado
        CHECK (estado IN ('BORRADOR', 'PUBLICADO', 'ARCHIVADO')),

    CONSTRAINT chk_cic_documento_tamano
        CHECK (tamano_bytes > 0)
);

CREATE INDEX idx_cic_documento_categoria
    ON cic_documento(categoria_id);

CREATE INDEX idx_cic_documento_estado
    ON cic_documento(estado);

CREATE INDEX idx_cic_documento_publicado
    ON cic_documento(publicado_en DESC);
