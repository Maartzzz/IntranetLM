
CREATE TABLE operation_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    operation_id BIGINT NOT NULL,

    actor_username VARCHAR(50) NOT NULL,
    actor_name VARCHAR(201) NOT NULL,

    action VARCHAR(40) NOT NULL,
    entity_type VARCHAR(20) NOT NULL,
    entity_id BIGINT,

    description VARCHAR(500) NOT NULL,
    old_value TEXT,
    new_value TEXT,

    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_operation_activity_operation
        FOREIGN KEY (operation_id) REFERENCES operations(id),

    CONSTRAINT ck_operation_activity_action
        CHECK (action IN (
            'CREATED',
            'UPDATED',
            'STATUS_CHANGED'
        )),

    CONSTRAINT ck_operation_activity_entity
        CHECK (entity_type IN (
            'OPERACION',
            'REQUISITO'
        ))
);

CREATE INDEX idx_operation_activity_operation_date
    ON operation_activity(operation_id, created_at DESC, id DESC);
