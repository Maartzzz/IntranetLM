VALUES ('OS_CLIENTE', 'O/S del cliente')
ON CONFLICT (code) DO NOTHING;

INSERT INTO statuses (process_type_id, name, description, color, active)
SELECT p.id, s.name, s.description, s.color, TRUE
FROM process_types p
CROSS JOIN (VALUES
    ('Recibida', 'La orden fue recibida del cliente.', '#64748B'),
    ('Confirmada', 'La orden está confirmada.', '#16A34A'),
    ('Llegó parcialmente', 'La carga llegó solo en parte.', '#D97706'),
    ('Cancelada', 'La orden fue cancelada.', '#DC2626')
) AS s(name, description, color)
WHERE p.code = 'OS_CLIENTE'
ON CONFLICT (process_type_id, name) DO NOTHING;

CREATE TABLE client_service_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_order_number VARCHAR(80) NOT NULL,
    client_id BIGINT NOT NULL,
    operation_id BIGINT,
    reference VARCHAR(120),
    service_type VARCHAR(3) NOT NULL,
    received_date DATE,
    estimated_arrival_date DATE,
    origin VARCHAR(200),
    destination VARCHAR(200),
    observation TEXT,
    status_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_client_service_orders_type CHECK (service_type IN ('FCL', 'LCL')),
    CONSTRAINT fk_client_service_orders_client FOREIGN KEY (client_id) REFERENCES clients(id),
    CONSTRAINT fk_client_service_orders_operation FOREIGN KEY (operation_id) REFERENCES operations(id),
    CONSTRAINT fk_client_service_orders_status FOREIGN KEY (status_id) REFERENCES statuses(id)
);

CREATE UNIQUE INDEX uq_client_service_orders_number_normalized
    ON client_service_orders(client_id, lower(trim(client_order_number)));

CREATE INDEX idx_client_service_orders_client ON client_service_orders(client_id);
CREATE INDEX idx_client_service_orders_operation ON client_service_orders(operation_id);
CREATE INDEX idx_client_service_orders_status ON client_service_orders(status_id);
CREATE INDEX idx_client_service_orders_received_date ON client_service_orders(received_date);

CREATE TABLE client_service_order_fcl_quantities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_service_order_id BIGINT NOT NULL,
    cargo_type_id BIGINT NOT NULL,
    total_quantity INTEGER NOT NULL,
    CONSTRAINT uq_client_service_order_fcl_type UNIQUE (client_service_order_id, cargo_type_id),
    CONSTRAINT ck_client_service_order_fcl_quantity CHECK (total_quantity > 0),
    CONSTRAINT fk_client_service_order_fcl_order FOREIGN KEY (client_service_order_id)
        REFERENCES client_service_orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_client_service_order_fcl_cargo_type FOREIGN KEY (cargo_type_id)
        REFERENCES cargo_types(id)
);

CREATE TABLE client_service_order_lcl_quantity (
    client_service_order_id BIGINT PRIMARY KEY,
    total_packages INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_client_service_order_lcl_packages CHECK (total_packages >= 0),
    CONSTRAINT fk_client_service_order_lcl_order FOREIGN KEY (client_service_order_id)
        REFERENCES client_service_orders(id) ON DELETE CASCADE
);

CREATE OR REPLACE FUNCTION set_client_service_order_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_client_service_orders_updated_at
BEFORE UPDATE ON client_service_orders
FOR EACH ROW EXECUTE FUNCTION set_client_service_order_updated_at();
