CREATE TABLE client_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_client_locations_client FOREIGN KEY (client_id) REFERENCES clients(id),
    CONSTRAINT fk_client_locations_location FOREIGN KEY (location_id) REFERENCES locations(id),
    CONSTRAINT uq_client_locations_pair UNIQUE (client_id, location_id),
    CONSTRAINT uq_client_locations_location UNIQUE (location_id)
);
CREATE INDEX idx_client_locations_client ON client_locations(client_id);
