CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type VARCHAR(10) NOT NULL,
    document_number VARCHAR(20) NOT NULL,
    business_name VARCHAR(200) NOT NULL,
    address VARCHAR(300),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    parent_client_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_clients_document UNIQUE (document_type, document_number),
    CONSTRAINT ck_clients_document_type CHECK (document_type IN ('RUC', 'DNI', 'CE')),
    CONSTRAINT fk_clients_parent FOREIGN KEY (parent_client_id) REFERENCES clients(id),
    CONSTRAINT ck_clients_not_own_parent CHECK (parent_client_id IS NULL OR parent_client_id <> id)
);

CREATE INDEX idx_clients_business_name ON clients (business_name);
CREATE INDEX idx_clients_active ON clients (active);
