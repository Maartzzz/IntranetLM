-- Relación muchos-a-muchos entre clientes principales y subclientes.
CREATE TABLE client_subclients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    subclient_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_client_subclients_client FOREIGN KEY (client_id) REFERENCES clients(id),
    CONSTRAINT fk_client_subclients_subclient FOREIGN KEY (subclient_id) REFERENCES clients(id),
    CONSTRAINT uq_client_subclients_pair UNIQUE (client_id, subclient_id),
    CONSTRAINT ck_client_subclients_distinct CHECK (client_id <> subclient_id)
);

CREATE INDEX idx_client_subclients_client ON client_subclients(client_id);
CREATE INDEX idx_client_subclients_subclient ON client_subclients(subclient_id);

-- Conserva las relaciones jerárquicas existentes antes de retirar el modelo 1:N anterior.
INSERT INTO client_subclients (client_id, subclient_id)
SELECT parent_client_id, id
FROM clients
WHERE parent_client_id IS NOT NULL
ON CONFLICT (client_id, subclient_id) DO NOTHING;

ALTER TABLE clients DROP CONSTRAINT IF EXISTS fk_clients_parent;
ALTER TABLE clients DROP CONSTRAINT IF EXISTS ck_clients_not_own_parent;
ALTER TABLE clients DROP COLUMN IF EXISTS parent_client_id;

-- Registro único de ubicaciones físicas.
CREATE TABLE locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    location_type VARCHAR(30) NOT NULL,
    address VARCHAR(300) NOT NULL,
    reference VARCHAR(300),
    district VARCHAR(100),
    province VARCHAR(100),
    department VARCHAR(100),
    latitude NUMERIC(10,7),
    longitude NUMERIC(10,7),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_locations_type CHECK (location_type IN ('ALMACEN', 'DEPOSITO', 'PUERTO', 'PLANTA', 'CENTRO_DISTRIBUCION', 'OTRO')),
    CONSTRAINT ck_locations_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_locations_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_locations_name ON locations(name);
CREATE INDEX idx_locations_active ON locations(active);

-- Condiciones operativas de una ubicación para cada relación cliente-subcliente.
CREATE TABLE client_subclient_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_subclient_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    usage_type VARCHAR(20) NOT NULL,
    contact_name VARCHAR(150),
    contact_phone VARCHAR(30),
    operating_hours VARCHAR(200),
    instructions TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_csl_client_subclient FOREIGN KEY (client_subclient_id) REFERENCES client_subclients(id),
    CONSTRAINT fk_csl_location FOREIGN KEY (location_id) REFERENCES locations(id),
    CONSTRAINT uq_csl_relation_location UNIQUE (client_subclient_id, location_id),
    CONSTRAINT ck_csl_usage_type CHECK (usage_type IN ('RECOJO', 'ENTREGA', 'AMBOS'))
);

CREATE INDEX idx_csl_relation ON client_subclient_locations(client_subclient_id);
CREATE INDEX idx_csl_location ON client_subclient_locations(location_id);


-- Catálogo especializado de almacenes. Cada almacén reutiliza una ubicación física.
-- La ubicación puede existir sin ser almacén y puede seguir vinculada a clientes/subclientes.
CREATE TABLE warehouses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL,
    warehouse_code VARCHAR(30) NOT NULL,
    warehouse_name VARCHAR(150) NOT NULL,
    warehouse_type VARCHAR(30) NOT NULL,
    operator_name VARCHAR(150) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    observations TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_warehouses_location FOREIGN KEY (location_id) REFERENCES locations(id),
    CONSTRAINT uq_warehouses_location UNIQUE (location_id),
    CONSTRAINT uq_warehouses_code UNIQUE (warehouse_code),
    CONSTRAINT ck_warehouses_type CHECK (warehouse_type IN ('ALMACEN_DEVOLUCION', 'ALMACEN_VACIOS', 'ALMACEN_CARGA', 'OTRO'))
);

CREATE INDEX idx_warehouses_name ON warehouses(warehouse_name);
CREATE INDEX idx_warehouses_active ON warehouses(active);
