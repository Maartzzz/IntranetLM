-- V26: catálogo de proveedores y relación con O/S internas.
CREATE TABLE providers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type VARCHAR(10) NOT NULL,
    document_number VARCHAR(11) NOT NULL,
    business_name VARCHAR(200) NOT NULL,
    contact_name VARCHAR(150),
    phone VARCHAR(30),
    email VARCHAR(150),
    address VARCHAR(300),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_providers_document UNIQUE (document_type, document_number),
    CONSTRAINT ck_providers_document_type CHECK (document_type IN ('DNI', 'RUC10', 'RUC20')),
    CONSTRAINT ck_providers_document_number CHECK (
        (document_type = 'DNI' AND document_number ~ '^[0-9]{8}$') OR
        (document_type = 'RUC10' AND document_number ~ '^10[0-9]{9}$') OR
        (document_type = 'RUC20' AND document_number ~ '^20[0-9]{9}$')
    )
);

CREATE INDEX idx_providers_active_business_name
    ON providers(active, business_name);

ALTER TABLE internal_service_orders
    ADD CONSTRAINT fk_internal_service_orders_provider
    FOREIGN KEY (provider_id) REFERENCES providers(id);

CREATE INDEX idx_internal_service_orders_provider
    ON internal_service_orders(provider_id);
