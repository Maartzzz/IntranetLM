ALTER TABLE operations
    ALTER COLUMN reference DROP NOT NULL,
    ADD COLUMN origin VARCHAR(200),
    ADD COLUMN destination VARCHAR(200),
    ADD COLUMN quantity INTEGER,
    ADD COLUMN status_id BIGINT;

-- Migrar el estado textual existente a su equivalente en el nuevo catálogo.
UPDATE operations o
SET status_id = s.id
FROM statuses s
JOIN process_types p ON p.id = s.process_type_id
WHERE p.code = 'OPERACION'
  AND lower(s.name) = CASE
      WHEN upper(o.status) = 'EN_SEGUIMIENTO' THEN 'en seguimiento'
      WHEN upper(o.status) = 'CONFIRMADA' THEN 'confirmada'
      WHEN upper(o.status) = 'FINALIZADA' THEN 'finalizada'
      WHEN upper(o.status) = 'CANCELADA' THEN 'cancelada'
      WHEN upper(o.status) = 'EN_PROGRAMACION' THEN 'en programación'
      ELSE 'registrada'
  END;

ALTER TABLE operations
    ADD CONSTRAINT fk_operations_status
        FOREIGN KEY (status_id) REFERENCES statuses(id);

-- La columna status_id se mantiene nullable por flexibilidad de transición.
-- Se retiran únicamente columnas de la estructura provisional que ya no pertenecen
-- a la definición acordada. No se eliminan filas.
ALTER TABLE operations
    DROP COLUMN status,
    DROP COLUMN description;

CREATE INDEX idx_operations_status_id ON operations(status_id);
