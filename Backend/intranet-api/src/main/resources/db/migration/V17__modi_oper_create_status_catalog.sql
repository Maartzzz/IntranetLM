-- No elimina registros ni modifica las migraciones V14, V15 o V16.

CREATE TABLE process_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE statuses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_type_id BIGINT NOT NULL,
    name VARCHAR(80) NOT NULL,
    description TEXT,
    color VARCHAR(20),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_statuses_process_type
        FOREIGN KEY (process_type_id) REFERENCES process_types(id),
    CONSTRAINT uq_statuses_process_name UNIQUE (process_type_id, name)
);

