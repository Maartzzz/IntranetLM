-- V16: Registro inicial de operaciones.
-- Una operación agrupa el contexto del caso; los servicios y viajes
-- se desarrollarán en módulos posteriores.

CREATE SEQUENCE operations_number_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

CREATE TABLE operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_number VARCHAR(20) NOT NULL,
    reference VARCHAR(150) NOT NULL,
    client_id BIGINT NOT NULL,
    cargo_type_id BIGINT NOT NULL,
    customer_order_number VARCHAR(100),
    description VARCHAR(500),
    estimated_date DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'EN_SEGUIMIENTO',
    observation VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_operations_operation_number UNIQUE (operation_number),
    CONSTRAINT fk_operations_client FOREIGN KEY (client_id) REFERENCES clients(id),
    CONSTRAINT fk_operations_cargo_type FOREIGN KEY (cargo_type_id) REFERENCES cargo_types(id)
);

CREATE INDEX idx_operations_client_id ON operations (client_id);
CREATE INDEX idx_operations_cargo_type_id ON operations (cargo_type_id);
CREATE INDEX idx_operations_created_at ON operations (created_at DESC);
CREATE INDEX idx_operations_estimated_date ON operations (estimated_date);
