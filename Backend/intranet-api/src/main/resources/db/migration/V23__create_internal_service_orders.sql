-- O/S interna: unidad programable independiente, asociacion opcional a O/S cliente.
CREATE SEQUENCE internal_service_order_number_seq START WITH 1 INCREMENT BY 1;
INSERT INTO process_types (code, name)
VALUES ('OS_INTERNA', 'O/S interna')
ON CONFLICT (code) DO NOTHING;

CREATE TABLE internal_service_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    internal_order_number BIGINT NOT NULL DEFAULT nextval('internal_service_order_number_seq') UNIQUE,
    client_id BIGINT NOT NULL,
    client_service_order_id BIGINT,
    service_type VARCHAR(3) NOT NULL,
    reference VARCHAR(120),
    origin_location_id BIGINT NOT NULL,
    destination_location_id BIGINT NOT NULL,
    provider_id BIGINT,
    scheduled_date DATE,
    status_id BIGINT,
    billing_status VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    observations TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_internal_service_orders_type CHECK (service_type IN ('FCL', 'LCL')),
    CONSTRAINT ck_internal_service_orders_billing CHECK (billing_status IN ('PENDIENTE', 'FACTURADO')),
    CONSTRAINT fk_internal_service_orders_client FOREIGN KEY (client_id) REFERENCES clients(id),
    CONSTRAINT fk_internal_service_orders_client_order FOREIGN KEY (client_service_order_id) REFERENCES client_service_orders(id),
    CONSTRAINT fk_internal_service_orders_origin FOREIGN KEY (origin_location_id) REFERENCES locations(id),
    CONSTRAINT fk_internal_service_orders_destination FOREIGN KEY (destination_location_id) REFERENCES locations(id),
    CONSTRAINT fk_internal_service_orders_status FOREIGN KEY (status_id) REFERENCES statuses(id)
);
CREATE INDEX idx_internal_service_orders_client ON internal_service_orders(client_id);
CREATE INDEX idx_internal_service_orders_client_order ON internal_service_orders(client_service_order_id);
CREATE INDEX idx_internal_service_orders_scheduled_date ON internal_service_orders(scheduled_date);
CREATE INDEX idx_internal_service_orders_status ON internal_service_orders(status_id);

-- Proveedor permanece sin FK hasta que exista y se valide el catalogo correspondiente.
CREATE TABLE internal_service_order_fcl (
    internal_service_order_id BIGINT PRIMARY KEY,
    container_number VARCHAR(40),
    cargo_type_id BIGINT,
    cubic_meters NUMERIC(10,3),
    empty_warehouse_location_id BIGINT,
    return_due_date DATE,
    memo TEXT,
    CONSTRAINT fk_internal_service_order_fcl_order FOREIGN KEY (internal_service_order_id)
        REFERENCES internal_service_orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_internal_service_order_fcl_cargo_type FOREIGN KEY (cargo_type_id) REFERENCES cargo_types(id),
    CONSTRAINT fk_internal_service_order_fcl_empty_location FOREIGN KEY (empty_warehouse_location_id) REFERENCES locations(id),
    CONSTRAINT ck_internal_service_order_fcl_cubic CHECK (cubic_meters IS NULL OR cubic_meters >= 0)
);

CREATE TABLE internal_service_order_lcl (
    internal_service_order_id BIGINT PRIMARY KEY,
    packages INTEGER,
    weight_kg NUMERIC(12,3),
    cubic_meters NUMERIC(12,3),
    CONSTRAINT fk_internal_service_order_lcl_order FOREIGN KEY (internal_service_order_id)
        REFERENCES internal_service_orders(id) ON DELETE CASCADE,
    CONSTRAINT ck_internal_service_order_lcl_packages CHECK (packages IS NULL OR packages >= 0),
    CONSTRAINT ck_internal_service_order_lcl_weight CHECK (weight_kg IS NULL OR weight_kg >= 0),
    CONSTRAINT ck_internal_service_order_lcl_cubic CHECK (cubic_meters IS NULL OR cubic_meters >= 0)
);

CREATE OR REPLACE FUNCTION set_internal_service_order_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_internal_service_orders_updated_at
BEFORE UPDATE ON internal_service_orders
FOR EACH ROW EXECUTE FUNCTION set_internal_service_order_updated_at();
