-- V18: Catálogo configurable y requisitos asociados exclusivamente a Operaciones.
-- No modifica ni elimina datos de migraciones anteriores.

INSERT INTO process_types (code, name)
VALUES ('REQUISITO', 'Requisito')
ON CONFLICT (code) DO NOTHING;

INSERT INTO statuses (process_type_id, name, description, color, active)
SELECT p.id, s.name, s.description, s.color, TRUE
FROM process_types p
CROSS JOIN (VALUES
    ('Pendiente', 'El requisito aún no ha sido gestionado.', '#64748B'),
    ('En seguimiento', 'Se está gestionando el requisito.', '#2563EB'),
    ('Completado', 'El requisito fue completado.', '#16A34A'),
    ('Bloqueado', 'El requisito no puede avanzar actualmente.', '#DC2626')
) AS s(name, description, color)
WHERE p.code = 'REQUISITO'
ON CONFLICT (process_type_id, name) DO NOTHING;

CREATE TABLE requirement_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_requirement_catalog_name UNIQUE (name)
);

CREATE TABLE operation_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id BIGINT NOT NULL,
    requirement_catalog_id BIGINT,
    custom_name VARCHAR(120),
    external_responsible VARCHAR(150),
    status_id BIGINT NOT NULL,
    comment TEXT,
    registered_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_operation_requirements_operation
        FOREIGN KEY (operation_id) REFERENCES operations(id),
    CONSTRAINT fk_operation_requirements_catalog
        FOREIGN KEY (requirement_catalog_id) REFERENCES requirement_catalog(id),
    CONSTRAINT fk_operation_requirements_status
        FOREIGN KEY (status_id) REFERENCES statuses(id),
    CONSTRAINT ck_operation_requirement_source CHECK (
        (requirement_catalog_id IS NOT NULL AND custom_name IS NULL)
        OR
        (requirement_catalog_id IS NULL AND custom_name IS NOT NULL AND length(trim(custom_name)) > 0)
    )
);

-- Impide repetir un mismo requisito del catálogo dentro de una operación.
CREATE UNIQUE INDEX uq_operation_requirement_catalog
    ON operation_requirements(operation_id, requirement_catalog_id)
    WHERE requirement_catalog_id IS NOT NULL;

-- Impide repetir requisitos personalizados por operación, ignorando mayúsculas
-- y espacios al inicio/final.
CREATE UNIQUE INDEX uq_operation_requirement_custom
    ON operation_requirements(operation_id, lower(trim(custom_name)))
    WHERE requirement_catalog_id IS NULL;

CREATE INDEX idx_operation_requirements_operation
    ON operation_requirements(operation_id);
CREATE INDEX idx_operation_requirements_status
    ON operation_requirements(status_id);

CREATE UNIQUE INDEX uq_requirement_catalog_name_normalized
    ON requirement_catalog(lower(trim(name)));

CREATE INDEX idx_requirement_catalog_active
    ON requirement_catalog(active, name);

CREATE OR REPLACE FUNCTION set_requirement_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_requirement_catalog_updated_at
BEFORE UPDATE ON requirement_catalog
FOR EACH ROW EXECUTE FUNCTION set_requirement_updated_at();

CREATE TRIGGER trg_operation_requirements_updated_at
BEFORE UPDATE ON operation_requirements
FOR EACH ROW EXECUTE FUNCTION set_requirement_updated_at();
